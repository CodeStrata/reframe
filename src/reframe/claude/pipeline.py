"""Pipeline 2, stage by stage (docs/pipeline-2.md, section 4). Its status lives under "claude" in run.json, beside
pipeline 1's, and every stage can be run again: what is done is skipped.

C0 preflight · C1 workspace · C2 plugin preflight · C3 assess and map · C4 rule extraction (behind the agent limit)
C5 retrieval · C6 requirements generated by Reframe · C7 Claude's graph in Neptune · C8 reports and the comparison
"""

from __future__ import annotations

from typing import Any

from reframe.core.errors import Outcome, Stop
from reframe.core.pipeline import Context
from reframe.core.runfolder import iso

STAGES = ("preflight", "workspace", "plugin preflight", "assess", "map", "estimate", "extract rules", "retrieve", "requirements",
          "graph", "report", "done")
DEFAULT_MAX_AGENTS = 600


def state(ctx: Context) -> dict[str, Any]:
    return dict(ctx.state.get("claude") or {})


def update(ctx: Context, **values: Any) -> dict[str, Any]:
    return ctx.folder.merge("claude", **values)  # under the run folder's records lock: pipeline 1 may be writing too


def stage(ctx: Context, name: str) -> None:
    update(ctx, stage=name, status="RUNNING", message=None, updated_at=iso())
    ctx.folder.event("claude_stage", stage=name)


def record_stop(ctx: Context, stop: Stop) -> None:
    update(ctx, status=stop.outcome.value, message=stop.message, updated_at=iso())
    ctx.folder.event("claude_stopped", outcome=stop.outcome.value, message=stop.message[:500])


def request(ctx: Context, *, auth: str = "subscription", max_agents: int | None = None, mode: str | None = None,
            graph_load: str | None = None) -> dict[str, Any]:
    """Record what pipeline 2 should do on this run; the worker reads it."""
    current = state(ctx)
    return update(ctx, requested_at=current.get("requested_at") or iso(), auth=auth or current.get("auth") or "subscription",
                  max_agents=int(max_agents or current.get("max_agents") or DEFAULT_MAX_AGENTS),
                  mode=mode or current.get("mode") or ctx.state.get("mode") or "autonomous",
                  graph_load=graph_load or current.get("graph_load"), status=current.get("status") or "REQUESTED")


def ready(ctx: Context) -> bool:
    """Pipeline 2 can start once pipeline 1 has the snapshot (stage 1) and the AWS resources (stage 2)."""
    return ctx.folder.exists("snapshot.json") and ctx.changes.receipt("terraform-project-apply") is not None


def wait_for_pipeline_1(ctx: Context, poll: float = 60, sleep=None) -> None:
    """The comparison needs AWS Transform's results. Waits for pipeline 1; if it stops, pipeline 2 stops and says why."""
    import time
    sleep = sleep or time.sleep
    while True:
        run = ctx.folder.state
        if run.get("status") == Outcome.DONE.value and run.get("retrieved_at"):
            return
        if run.get("torn_down"):
            raise Stop(Outcome.REFUSED, "the run was torn down before AWS Transform's results were retrieved")
        status = str(run.get("status"))
        if status not in ("RUNNING", "None") and not ctx.folder.worker_pid("run"):
            raise Stop(Outcome.WAITING_HUMAN, f"pipeline 1 stopped ({status}: {str(run.get('message') or '')[:200]}). Claude's review is "
                                              "ready; reframe resume continues pipeline 1, and the comparison follows when it is done")
        sleep(poll)


def claude_code(ctx: Context):
    from reframe.claude import plugin
    from reframe.claude.runner import ClaudeCode, environment
    from reframe.claude.workspace import paths
    places = paths(ctx.folder)
    settings = state(ctx)
    auth = settings.get("auth", "subscription")
    env = environment(auth, aws_credentials=ctx.aws.credentials_environment if auth == "bedrock" else None, region=ctx.state.get("region"))
    return ClaudeCode(places["root"], places["policy"], plugin.plugin_dir(), places["logs"], env)


def ask(ctx: Context):
    from reframe.claude.steps import wait_for_answer

    def asker(qid: str, text: str, options: list[str]) -> str:
        update(ctx, status=Outcome.WAITING_HUMAN.value, message=f"waiting for reframe answer: {text.splitlines()[0][:200]}")
        reply = wait_for_answer(ctx.folder, qid, text, options)
        update(ctx, status="RUNNING", message=None)
        return reply
    return asker


def work(ctx: Context) -> Outcome:
    from reframe.claude import preflight, steps
    from reframe.claude import workspace as ws
    run = ctx.state
    if not ready(ctx):
        raise Stop(Outcome.REFUSED, "pipeline 1 has not made the run's snapshot and AWS resources yet; pipeline 2 starts when it has")
    if run.get("torn_down"):
        raise Stop(Outcome.REFUSED, "this run is torn down; pipeline 2 needs the run's snapshot and Neptune graph")
    settings = state(ctx)
    mode = settings.get("mode", run.get("mode", "autonomous"))
    update(ctx, started_at=settings.get("started_at") or iso())

    stage(ctx, "preflight")
    report = preflight.check(settings.get("auth", "subscription"), aws_identity=ctx.aws.identity)
    ctx.folder.save("claude-preflight.json", report.as_json())
    if not report.ok:
        signin = any(not c.ok and "sign-in" in c.name for c in report.checks)
        raise Stop(Outcome.WAITING_SIGNIN if signin else Outcome.REFUSED, report.problems())

    stage(ctx, "workspace")
    made = ws.create(ctx.folder)
    from reframe.claude import plugin
    update(ctx, workspace=made["workspace"], sha256=made["sha256"], files=made["files"],
           plugin={"name": plugin.NAME, "version": plugin.VERSION, "commit": plugin.COMMIT})
    places = ws.paths(ctx.folder)
    claude = claude_code(ctx)
    system = run["project"]

    stage(ctx, "plugin preflight")
    answers = steps.preflight_answers(ctx.folder, mode, made["sha256"], ask(ctx))
    steps.run_step(ctx.folder, claude, places["analysis"], "preflight", steps.preflight_prompt(system, answers))
    stage(ctx, "assess")
    steps.run_step(ctx.folder, claude, places["analysis"], "assess", f"{steps.PREFIX}assess {system}")
    stage(ctx, "map")
    steps.run_step(ctx.folder, claude, places["analysis"], "map", f"{steps.PREFIX}map {system}")

    stage(ctx, "estimate")
    size = ctx.folder.load("claude-estimate.json")
    if not size:
        size = steps.estimate(places["root"], claude.plugin, system, claude.env)
        ctx.folder.save("claude-estimate.json", size)
    limit = int(state(ctx).get("max_agents") or DEFAULT_MAX_AGENTS)
    approved = state(ctx).get("estimate_approved")
    if not approved and (mode == "interactive" or size["agents_high"] > limit):
        reply = ask(ctx)("claude-estimate", f"Rule extraction will run {size['shards']} shards: about {size['agents_low']} to "
                         f"{size['agents_high']} agents, up to about {size['tokens_high'] / 1e6:.1f} million tokens and "
                         f"{size['minutes_high']} minutes on your Claude account. The agent limit is {limit}.",
                         [f"Run it (raises the limit for this run to {max(limit, size['agents_high'])})", "Cancel pipeline 2 for now"])
        if reply.startswith("Cancel"):
            raise Stop(Outcome.REFUSED, "rule extraction was cancelled at the estimate; reframe claude starts it again")
        limit = max(limit, size["agents_high"])
        update(ctx, max_agents=limit)
    update(ctx, estimate_approved=iso(), estimate=size)
    ctx.folder.decide("claude-estimate", f"run {size['shards']} shards", f"the upper estimate ({size['agents_high']} agents) is within "
                      f"the agent limit ({limit})", step="claude rule extraction")

    stage(ctx, "extract rules")
    steps.run_step(ctx.folder, claude, places["analysis"], "extract-rules", steps.extract_prompt(system, size, limit),
                   resume_prompt=steps.extract_resume_prompt(system), system=system)
    changed = ws.changed(ctx.folder)
    if changed:
        raise Stop(Outcome.FAILED, f"{len(changed)} file(s) in the snapshot changed during the plugin's steps (for example {changed[0]}); "
                                   "its results are not used")
    update(ctx, source_unchanged=iso())

    stage(ctx, "retrieve")
    from reframe.claude import retrieve
    model = retrieve.save(ctx.folder)
    if not model["rules"]:
        raise Stop(Outcome.FAILED, "the plugin's BUSINESS_RULES.md has no rule cards Reframe could read")

    stage(ctx, "requirements")
    from reframe.claude import requirements
    generated = requirements.generate(ctx.folder, claude, model)

    stage(ctx, "graph")
    from reframe.claude import load
    load.graph(ctx, model, generated)

    stage(ctx, "report")
    from reframe.report import build, compare
    path = build.build_claude(ctx.folder)
    update(ctx, report=str(path.relative_to(ctx.folder.root)))
    stage(ctx, "waiting for AWS Transform")
    wait_for_pipeline_1(ctx)
    stage(ctx, "comparison")
    compare.pair_with_ai(ctx.folder, claude)
    comparison = compare.build(ctx.folder)
    build.build(ctx.folder)  # AWS Transform's review gains its links to Claude's review and the comparison
    update(ctx, stage="done", status=Outcome.DONE.value, report=str(path.relative_to(ctx.folder.root)),
           comparison=str(comparison.relative_to(ctx.folder.root)), finished_at=iso(),
           message=f"Claude's business review: {path}. The comparison: {comparison}.")
    ctx.folder.event("claude_done")
    return Outcome.DONE
